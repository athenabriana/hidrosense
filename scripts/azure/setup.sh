#!/usr/bin/env bash
# Provisions the AKS target for the pipeline and wires GitHub to it via OIDC.
# Idempotent: rerunning reuses what exists and keeps the secrets stored in .env.azure.
#
# Prereqs: az login (Azure for Students), gh auth login, openssl.
# Usage:   scripts/azure/setup.sh
# Optional env: AZURE_REGION (chilecentral), AKS_RESOURCE_GROUP (hidrosense-rg),
#               AKS_CLUSTER_NAME (hidrosense-aks), AKS_NODE_SIZE (Standard_B2s_v2)
set -euo pipefail
export MSYS_NO_PATHCONV=1   # Git Bash on Windows would mangle /subscriptions/... scopes

REGION="${AZURE_REGION:-chilecentral}"
RG="${AKS_RESOURCE_GROUP:-hidrosense-rg}"
CLUSTER="${AKS_CLUSTER_NAME:-hidrosense-aks}"
NODE_SIZE="${AKS_NODE_SIZE:-Standard_B2s_v2}"
IDENTITY="hidrosense-github"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
ENV_FILE="$ROOT/.env.azure"

REPO="$(gh repo view --json nameWithOwner -q .nameWithOwner)"
SUB_ID="$(az account show --query id -o tsv)"
TENANT_ID="$(az account show --query tenantId -o tsv)"
echo "==> Assinatura $(az account show --query name -o tsv) | repo $REPO | região $REGION"

echo "==> Registrando providers"
for p in Microsoft.ContainerService Microsoft.ManagedIdentity Microsoft.Network Microsoft.Compute; do
  az provider register --namespace "$p" --wait >/dev/null
done

echo "==> Resource group $RG"
az group create -n "$RG" -l "$REGION" -o none

if az aks show -g "$RG" -n "$CLUSTER" -o none 2>/dev/null; then
  echo "==> Cluster $CLUSTER já existe"
else
  # Cilium enforces the NetworkPolicy that isolates SQL Server (k8s/base/networkpolicy.yaml).
  # Two nodes: AKS system pods reserve ~1 vCPU, so one 2-vCPU node can't fit both environments.
  echo "==> Criando AKS $CLUSTER (2 nós $NODE_SIZE, tier free) — leva ~5-10 min"
  az aks create -g "$RG" -n "$CLUSTER" -l "$REGION" \
    --tier free \
    --node-count 2 --node-vm-size "$NODE_SIZE" \
    --network-plugin azure --network-plugin-mode overlay \
    --network-dataplane cilium --network-policy cilium \
    --no-ssh-key -o none
fi
AKS_ID="$(az aks show -g "$RG" -n "$CLUSTER" --query id -o tsv)"

# User-assigned managed identity instead of an app registration: works on tenants
# (like school ones) that block creating Entra applications.
echo "==> Identidade gerenciada $IDENTITY + credenciais federadas (OIDC)"
az identity create -g "$RG" -n "$IDENTITY" -o none
CLIENT_ID="$(az identity show -g "$RG" -n "$IDENTITY" --query clientId -o tsv)"
PRINCIPAL_ID="$(az identity show -g "$RG" -n "$IDENTITY" --query principalId -o tsv)"
# GitHub may send the subject as owner@id/repo@id (immutable IDs) or owner/repo; trust both.
REPO_IDS="$(gh api "repos/$REPO" --jq '"\(.owner.login)@\(.owner.id)/\(.name)@\(.id)"')"
for env in staging production; do
  for pair in "github-$env:$REPO" "github-$env-ids:$REPO_IDS"; do
    name="${pair%%:*}"
    az identity federated-credential show -g "$RG" --identity-name "$IDENTITY" -n "$name" -o none 2>/dev/null && continue
    az identity federated-credential create -g "$RG" --identity-name "$IDENTITY" \
      -n "$name" \
      --issuer https://token.actions.githubusercontent.com \
      --subject "repo:${pair#*:}:environment:$env" \
      --audiences api://AzureADTokenExchange -o none
  done
done

echo "==> Permissão no cluster (Azure Kubernetes Service Cluster User Role)"
for _ in $(seq 1 10); do
  az role assignment create --assignee-object-id "$PRINCIPAL_ID" --assignee-principal-type ServicePrincipal \
    --role "Azure Kubernetes Service Cluster User Role" --scope "$AKS_ID" -o none 2>/dev/null && break
  sleep 10   # new identities take a moment to replicate
done

echo "==> Variáveis do repositório (IDs, não são segredos)"
gh variable set AZURE_CLIENT_ID --body "$CLIENT_ID"
gh variable set AZURE_TENANT_ID --body "$TENANT_ID"
gh variable set AZURE_SUBSCRIPTION_ID --body "$SUB_ID"
gh variable set AZURE_REGION --body "$REGION"
gh variable set AKS_RESOURCE_GROUP --body "$RG"
gh variable set AKS_CLUSTER_NAME --body "$CLUSTER"

# Secrets must stay stable: the SQL Server volume keeps the SA password from the first deploy.
# Generated once, kept only in the gitignored .env.azure and in GitHub environment secrets.
gen() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | cut -c1-32; }
if [ ! -f "$ENV_FILE" ]; then
  echo "==> Gerando segredos em .env.azure (fora do git)"
  umask 077
  {
    echo "# Generated by scripts/azure/setup.sh. Do not commit or share."
    for env in STAGING PRODUCTION; do
      echo "${env}_DB_PASSWORD=Db#1$(gen)"
      echo "${env}_JWT_SECRET_KEY=$(gen)$(gen)"
      echo "${env}_SEED_ADMIN_PASSWORD=Ad#1$(gen)"
      echo "${env}_SEED_OPERATOR_PASSWORD=Op#1$(gen)"
    done
  } > "$ENV_FILE"
else
  echo "==> Reutilizando segredos de .env.azure"
fi
# shellcheck disable=SC1090
set -a; . "$ENV_FILE"; set +a

echo "==> Secrets dos environments staging/production (valores via stdin, sem eco)"
for env in staging production; do
  up="$(echo "$env" | tr '[:lower:]' '[:upper:]')"
  for k in DB_PASSWORD JWT_SECRET_KEY SEED_ADMIN_PASSWORD SEED_OPERATOR_PASSWORD; do
    var="${up}_$k"
    printf '%s' "${!var}" | gh secret set "$k" --env "$env"
  done
done

echo
echo "Pronto. Próximo push em develop/main faz deploy no AKS."
echo "  staging:   http://hidrosense-staging-athenabriana.$REGION.cloudapp.azure.com/swagger"
echo "  produção:  http://hidrosense-athenabriana.$REGION.cloudapp.azure.com/health"
echo "Senhas de login (admin/operador) estão em .env.azure."
echo "Depois da avaliação: scripts/azure/teardown.sh (evita consumir o crédito)."
